using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace CleanPC.Pro
{
    /// <summary>Exports the current scan (and recent cleaning history) to HTML or CSV.</summary>
    public static class ReportExporter
    {
        public static void ExportCsv(string path, IEnumerable<Target> targets, IEnumerable<Target> report)
        {
            var sb = new StringBuilder();
            sb.AppendLine("Type,Name,Category,Risk,Drive,Bytes,Size,Ticked,Items,Note,Status");
            foreach (var t in targets.Concat(report))
                sb.AppendLine(string.Join(",", new[] {
                    Fmt.Csv(t.Kind == TargetKind.Report ? "report-only" : "cleanup"), Fmt.Csv(t.Name), Fmt.Csv(t.Category), Fmt.Csv(t.RiskText), Fmt.Csv(t.Drive),
                    Math.Max(0, t.Size).ToString(), Fmt.Csv(Fmt.Size(t.Size)), t.IsChecked ? "yes" : "no", t.PathCount.ToString(), Fmt.Csv(t.Note), Fmt.Csv(t.Status) }));
            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(true));
        }

        public static void ExportHtml(string path, IEnumerable<Target> targets, IEnumerable<Target> report)
        {
            var tl = targets.ToList(); var rl = report.ToList();
            long total = tl.Where(t => t.Size > 0).Sum(t => t.Size), ticked = tl.Where(t => t.IsChecked && t.Size > 0).Sum(t => t.Size);
            var sb = new StringBuilder();
            sb.Append("<!doctype html><html><head><meta charset=\"utf-8\"><title>PC Cache Cleaner Pro report</title><style>");
            sb.Append("body{font:14px Segoe UI,Arial,sans-serif;margin:24px;color:#222}h1{font-size:20px}table{border-collapse:collapse;width:100%;margin:12px 0}");
            sb.Append("th,td{border:1px solid #ccc;padding:5px 8px;text-align:left;vertical-align:top}th{background:#f0f0f0}.r{color:#b00020;font-weight:600}.o{color:#9a6700}.s{color:#1a7f37}.n{text-align:right;white-space:nowrap}");
            sb.Append("</style></head><body>");
            sb.Append("<h1>PC Cache Cleaner Pro " + Fmt.Html(AppInfo.InformationalVersion) + " - scan report</h1>");
            sb.Append("<p>" + DateTime.Now.ToString("yyyy-MM-dd HH:mm") + " &middot; " + Environment.MachineName + " &middot; admin: " + AppInfo.IsAdmin + "</p>");
            sb.Append("<p>Cleanup rows: " + tl.Count + " &middot; total found: <b>" + Fmt.Size(total) + "</b> &middot; currently ticked: <b>" + Fmt.Size(ticked) + "</b></p>");
            sb.Append("<h2>Cleanup items</h2><table><tr><th>Item</th><th>Category</th><th>Risk</th><th>Drive</th><th class=n>Size</th><th>Ticked</th><th>Note / result</th></tr>");
            foreach (var t in tl)
            {
                string cls = t.Risk == Risk.Risky ? "r" : t.Risk == Risk.Optional ? "o" : "s";
                sb.Append("<tr><td>" + Fmt.Html(t.Name) + "</td><td>" + Fmt.Html(t.Category) + "</td><td class=" + cls + ">" + t.RiskText + "</td><td>" + Fmt.Html(t.Drive) + "</td><td class=n>" + Fmt.Size(t.Size) + "</td><td>" + (t.IsChecked ? "yes" : "no") + "</td><td>" + Fmt.Html(string.IsNullOrEmpty(t.Status) ? t.Note : t.Status) + "</td></tr>");
            }
            sb.Append("</table><h2>Report only (never deleted by this tool)</h2><table><tr><th>Item</th><th class=n>Size</th><th>Location</th><th>How to deal with it</th></tr>");
            foreach (var t in rl)
                sb.Append("<tr><td>" + Fmt.Html(t.Name) + "</td><td class=n>" + Fmt.Size(t.Size) + "</td><td>" + Fmt.Html(t.PathsText) + "</td><td>" + Fmt.Html(t.Note) + "</td></tr>");
            sb.Append("</table><h2>Recent cleanings</h2><table><tr><th>When</th><th>Mode</th><th>Drives</th><th>Items</th><th class=n>Freed</th></tr>");
            foreach (var c in CleanHistory.All().Take(25))
                sb.Append("<tr><td>" + Fmt.Html(c.Time.Replace('T', ' ')) + "</td><td>" + Fmt.Html(c.Mode) + "</td><td>" + Fmt.Html(c.Drives) + "</td><td>" + c.Items + "</td><td class=n>" + Fmt.Size(c.Freed) + "</td></tr>");
            sb.Append("</table><p style=\"color:#666\">Only regenerable cache/temp data is ever deleted. Generated by PC Cache Cleaner Pro.</p></body></html>");
            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
        }
    }
}
